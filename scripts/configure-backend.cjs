// Copies public application configuration only. Never bundles the .env file.
const fs = require("node:fs");
const path = require("node:path");
const input = process.argv[2];
if (!input) throw new Error("Pass the ND dashboard .env.local path.");
const text = fs.readFileSync(input, "utf8");
function value(name) {
  const line = text.split(/\r?\n/).find((line) => line.startsWith(`${name}=`));
  return (line || "").slice(name.length + 1).trim().replace(/^(["'])(.*)\1$/, "$2");
}
const url = value("NEXT_PUBLIC_SUPABASE_URL");
const publishableKey = value("NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY");
if (url !== "https://xtefjnfdjnxwrpkoydaj.supabase.co" || !/^sb_publishable_[A-Za-z0-9_-]{16,200}$/.test(publishableKey)) {
  throw new Error("Expected the selected shared project and a modern public publishable key. No file changed.");
}
fs.writeFileSync(path.join(__dirname, "..", "backend-public-config.js"),
  `/* Public app identity only; generated by scripts/configure-backend.cjs. */\nglobalThis.FudgeBackendPublicConfig = Object.freeze(${JSON.stringify({ url, publishableKey })});\n`);
console.log("Configured the shared backend using public app identity only. No secrets printed.");
